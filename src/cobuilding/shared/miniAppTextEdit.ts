/**
 * Edit mode for a tool's text (POC): the contracts every part of the feature
 * shares. Design and tickets: docs/design/mini-app-text-edit-poc.md.
 *
 * The user clicks text inside a running tool and types over it. The change is
 * written into the tool's own source, so the source stays the one place the
 * text lives and Claude sees the edit the next time it opens the file. Four
 * parts, four owners:
 *
 *   build   — every host element written in JSX is stamped with where it was
 *             written (`MINI_APP_SRC_ATTR`, from esbuild's jsxDEV source info)
 *   frame   — an injected shim turns the tool into an editable surface and
 *             reports what was edited (`EDIT_MSG`, postMessage)
 *   host    — MiniAppViewer draws the edit bar and relays frame messages to main
 *   main    — resolves the text to one literal in the tool's source, rewrites
 *             it, verifies by re-parsing and rebuilding (`TEXT_EDIT_IPC`)
 *
 * Zero model calls on every path. The one path that can lead to a model call
 * ("ask Claude to change computed text") only fills the composer; the user
 * still has to send it.
 */

/**
 * Attribute stamped on every host (lowercase-tag) element written in JSX:
 * `"<workspace-relative file>:<line>:<column>"`, e.g.
 * `".applications/geneExplorer/src/App.tsx:42:7"`. Line and column are
 * 1-based; the column counts UTF-16 code units (measured: esbuild's jsxDEV
 * `columnNumber`, which matches TypeScript's `getLineAndCharacterOfPosition`
 * + 1) and points at the `<` of the opening tag.
 */
export const MINI_APP_SRC_ATTR = 'data-acabox-src';

/** Longest replacement text accepted, in characters. */
export const MAX_EDIT_TEXT_CHARS = 2000;

/** At most this many ancestor stamps travel with a target. */
export const MAX_ANCESTOR_SRCS = 16;

/** `editId` / `probeId` format. Generated by the frame, opaque to everyone else. */
export const EDIT_ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/;

/** What the user pointed at: one rendered text node and where it sits. */
export interface TextEditTarget {
  /** The text node's value exactly as rendered (`Text.nodeValue` before editing). */
  text: string;
  /** `MINI_APP_SRC_ATTR` of the text node's parent element, or null when it has none. */
  elementSrc: string | null;
  /** Lowercase tag name of the text node's parent element. */
  tagName: string;
  /**
   * `MINI_APP_SRC_ATTR` values of the parent element's ancestors, nearest
   * first, consecutive duplicates removed, at most `MAX_ANCESTOR_SRCS`.
   * Excludes `elementSrc` itself.
   */
  ancestorSrcs: string[];
}

/** How the text is written in the source. */
export type TextEditKind =
  /** `<h1>Gene explorer</h1>` */
  | 'jsx-text'
  /** `<Card title="Gene explorer" />` */
  | 'jsx-attribute'
  /** `<p>{loading ? "Loading…" : "Ready"}</p>` */
  | 'jsx-expression'
  /** `{ label: "Gene explorer" }` */
  | 'object-property';

/** Why a direct edit was refused. Each has a plain-language `message` beside it. */
export type TextEditRefusal =
  /** No literal in the tool's source produces this text: it is built while the tool runs. */
  | 'computed'
  /** Several literals could produce it and nothing says which one was clicked. */
  | 'ambiguous'
  /** The literal is also used by the code itself (compared, looked up, a key). */
  | 'used-by-code'
  /** Only found outside the tool's own src/ (a shared component or a library). */
  | 'outside-tool'
  /** Bad request: empty target, text too long, bad tool name, bad id. */
  | 'invalid'
  /** The source no longer contains the text (it changed since the last build). */
  | 'changed'
  /** Written, but the tool no longer built afterwards; the write was reverted. */
  | 'build-failed';

/** Where an edit landed. */
export interface TextEditLocation {
  /** Path relative to the tool's directory, e.g. `"src/App.tsx"`. */
  file: string;
  /** 1-based line of the literal's start in the file. */
  line: number;
  kind: TextEditKind;
}

export type TextEditProbeResult =
  | { editable: true; location: TextEditLocation }
  | { editable: false; reason: TextEditRefusal; message: string };

export interface TextEditApplyRequest extends TextEditTarget {
  editId: string;
  /** The text to show instead. Newlines are folded to spaces before use. */
  newText: string;
}

export type TextEditApplyResult =
  | {
    ok: true;
    editId: string;
    location: TextEditLocation;
    /** Edits that `undo` can take back for this tool, after this one. */
    undoDepth: number;
    /**
     * True when the literal is a direct child of the clicked element's own JSX
     * (`jsx-text` / `jsx-expression` resolved at `elementSrc`). Every other
     * rendered element carrying the same `elementSrc` and the same old text
     * comes from that same literal, so the frame may update them in place.
     */
    sameElementScope: boolean;
  }
  | { ok: false; editId: string; reason: TextEditRefusal; message: string; undoDepth: number };

export type TextEditUndoResult =
  | { ok: true; editId: string; location: TextEditLocation; undoDepth: number }
  | { ok: false; message: string; undoDepth: number };

/** Renderer → main, `ipcRenderer.invoke`. Exposed as `window.miniAppsAPI.textEdit`. */
export const TEXT_EDIT_IPC = {
  /** (dirName, target: TextEditTarget) → TextEditProbeResult. Reads only. */
  probe: 'miniApps:textEdit:probe',
  /** (dirName, req: TextEditApplyRequest) → TextEditApplyResult. Writes, then builds. */
  apply: 'miniApps:textEdit:apply',
  /** (dirName) → TextEditUndoResult. Reverts the latest applied edit, then builds. */
  undo: 'miniApps:textEdit:undo',
  /** (dirName) → number of edits undo can take back. */
  undoDepth: 'miniApps:textEdit:undoDepth',
} as const;

/**
 * Frame ↔ host protocol over `window.postMessage`, between the tool's iframe
 * (the injected edit shim) and MiniAppViewer. The host accepts frame messages
 * only from its own iframe (`event.source === iframe.contentWindow`) and
 * ignores `probe` / `commit` / `suggest` / `shortcut` while edit mode is off.
 */
export const EDIT_MSG = {
  // ── host → frame ──
  /** `{ on: boolean }` — enter or leave edit mode. Idempotent. */
  mode: 'acabox:edit:mode',
  /** `{ probeId: string; editable: boolean }` — answer to `probe`. */
  probeResult: 'acabox:edit:probeResult',
  /** `{ editId: string; ok: boolean; sameElementScope?: boolean }` — answer to `commit`. */
  applyResult: 'acabox:edit:applyResult',
  /** `{ editId: string }` — an applied edit was undone; put the old text back if possible. */
  revert: 'acabox:edit:revert',

  // ── frame → host ──
  /** `{}` — the shim is installed in a fresh document; the host re-sends `mode`. */
  ready: 'acabox:edit:ready',
  /**
   * `{ on: boolean; stamped: number; final: boolean }` — sent on every `mode`.
   * `stamped` counts elements carrying `MINI_APP_SRC_ATTR`. When it is 0 the
   * shim keeps watching the DOM for up to 4 s and sends a second report with
   * `final: true`; only a final 0 means "this bundle was built without stamps".
   */
  state: 'acabox:edit:state',
  /** `{ probeId: string; target: TextEditTarget }` — the user clicked this text. */
  probe: 'acabox:edit:probe',
  /** `{ editId: string; target: TextEditTarget; newText: string }` — apply this edit. */
  commit: 'acabox:edit:commit',
  /** `{ oldText: string; newText: string }` — a change to text that cannot be edited directly. */
  suggest: 'acabox:edit:suggest',
  /** `{ action: 'undo' | 'done' }` — ⌘Z / Esc pressed in the frame while no text is being edited. */
  shortcut: 'acabox:edit:shortcut',
  /** `{ editId: string; ok: boolean }` — answer to `revert`; false means the text node was gone. */
  reverted: 'acabox:edit:reverted',
} as const;
